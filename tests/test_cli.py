        job = self.job_id()
        plan_path = self.root / f"state/ydl/jobs/{job}.json"
        plan = json.loads(plan_path.read_text())
        item = plan["items"][0]
        saved = self.output / f".ydl-partials/{job}/1" / item["source"]
        self.assertEqual(saved.read_text(), "not media")
        del item["mp3_tags"]
        mp3 = self.output / "Sample song.mp3"
        calls = self.calls()
        for expected in ({"title": "Sample song"}, {}):
            if not expected:
                del item["raw_title"]
            plan_path.write_text(json.dumps(plan))
            saved.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(self.root / "source.wav", saved)
            self.check_code(self.invoke("retry", job), 0)
            self.assertEqual(self.calls(), calls)
            self.assert_mp3_tags(mp3, **expected)
            mp3.unlink()

