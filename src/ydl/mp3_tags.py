"""Resolve the three MP3 tags managed by ydl."""

MANAGED_TAGS = ("title", "artist", "album")
PROVIDER = "Provided to YouTube by "
AUTO_GENERATED = "Auto-generated by YouTube."


def usable_text(value):
    if not isinstance(value, str) or "\x00" in value or not value.strip():
        return None
    try:
        value.encode("utf-8")
    except UnicodeEncodeError:
        return None
    return value


def auto_generated_music(description):
    if not isinstance(description, str):
        return False
    lines = [text for line in description.splitlines() if (text := line.strip())]
    return (bool(lines) and lines[0].startswith(PROVIDER) and lines[-1] == AUTO_GENERATED
            and sum(PROVIDER in line for line in lines) == 1
            and sum(AUTO_GENERATED in line for line in lines) == 1)


def youtube_candidates(info, raw_title):
    info = info or {}
    title = usable_text(info.get("title"))
    track = usable_text(info.get("track"))
    if not (title and track and title.strip() == track.strip() and auto_generated_music(info.get("description"))):
        fallback = title or raw_title
        return {"title": fallback} if fallback else {}
    candidates = {"title": track}
    artists = info.get("artists")
    if isinstance(artists, list):
        artist = " / ".join(text for value in artists if (text := usable_text(value)) is not None)
        if artist:
            candidates["artist"] = artist
    if album := usable_text(info.get("album")):
        candidates["album"] = album
    return candidates


def resolve(*sources):
    """Take the first usable value per managed tag from mappings in precedence order."""
    tags = {}
    for source in sources:
        for key, value in source.items():
            key = key.lower()
            if key in MANAGED_TAGS and (text := usable_text(value)) is not None:
                tags.setdefault(key, text)
    return tags
